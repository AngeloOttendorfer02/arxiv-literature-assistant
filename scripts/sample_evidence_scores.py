"""D069: how many real chunks and abstracts would the evidence guard remove at a threshold?

Draws a seeded random sample of chunks and paper abstracts through the read-only app login
(DATABASE_URL), scores them like the pipeline does (title plus text, as retrieval builds the
evidence) and writes scores and ids only, never any text, to
eval/results/evidence_real_sample.json and docs/evidence_real_sample.md.

    uv run --group rag --group guardrails python scripts/sample_evidence_scores.py
"""

import argparse
import json
import os
import time
from pathlib import Path

import psycopg
from dotenv import find_dotenv, load_dotenv

from scilitrag.evaluation.guardrail_eval import rate

PROJECT_ROOT = Path(__file__).resolve().parents[1]
RESULT = PROJECT_ROOT / "eval" / "results" / "evidence_real_sample.json"
REPORT = PROJECT_ROOT / "docs" / "evidence_real_sample.md"
THRESHOLDS = (0.001, 0.002, 0.005, 0.01, 0.02, 0.05, 0.1, 0.5, 0.9)
QUANTILES = (0.5, 0.9, 0.95, 0.99)
CHUNKS_SQL = (
    "SELECT c.chunk_id, c.corpus_id, c.section, c.text, p.title, p.year "
    "FROM chunks c JOIN papers p USING (corpus_id) "
    "ORDER BY md5(c.chunk_id || %(seed)s) LIMIT %(n)s"
)
PAPERS_SQL = (
    "SELECT corpus_id, title, abstract, year, true AS has_indexed_chunks "
    "FROM papers WHERE abstract IS NOT NULL AND abstract <> '' "
    "ORDER BY md5(corpus_id::text || %(seed)s) LIMIT %(n)s"
)


def fetch(dsn: str, seed: str, chunks: int, papers: int):
    with psycopg.connect(dsn, connect_timeout=10) as conn:
        conn.read_only = True
        cur = conn.cursor(row_factory=psycopg.rows.dict_row)
        return (
            cur.execute(CHUNKS_SQL, {"seed": seed, "n": chunks}).fetchall(),
            cur.execute(PAPERS_SQL, {"seed": seed, "n": papers}).fetchall(),
        )


def quantile(values: list[float], q: float) -> float:
    ordered = sorted(values)
    return ordered[min(int(q * len(ordered)), len(ordered) - 1)]


def summarize(records: list[dict]) -> dict:
    result = {}
    for kind in ("chunk", "paper"):
        scores = [r["score"] for r in records if r["type"] == kind]
        result[kind] = {
            "n": len(scores),
            "quantiles": {str(q): quantile(scores, q) for q in QUANTILES},
            "max": max(scores),
            "removed": {str(t): rate(sum(s >= t for s in scores), len(scores)) for t in THRESHOLDS},
        }
    return result


def report(summary: dict, meta: dict) -> str:
    lines = [
        "# Evidence guard on real chunks and abstracts (D069)",
        "",
        (
            f"Seeded random sample (seed `{meta['seed']}`) from the full database: "
            f"{summary['chunk']['n']} chunks and {summary['paper']['n']} paper abstracts, scored "
            "as the pipeline builds the evidence (title plus text). Scores and ids only are "
            "stored in `eval/results/evidence_real_sample.json`. Generated by "
            "`scripts/sample_evidence_scores.py`."
        ),
        "",
        (
            "Share of sampled real sources the evidence guard would remove (95 percent Wilson "
            "interval):"
        ),
        "",
        "| Threshold | Chunks | Abstracts |",
        "| ---: | --- | --- |",
    ]
    for t in THRESHOLDS:
        cells = []
        for kind in ("chunk", "paper"):
            r = summary[kind]["removed"][str(t)]
            low, high = r["ci95"]
            cells.append(
                f"{100 * r['rate']:.1f} % ({r['hits']}/{r['total']}, "
                f"CI {100 * low:.1f} to {100 * high:.1f})"
            )
        lines.append(f"| {t} | {cells[0]} | {cells[1]} |")
    lines += [
        "",
        "Score quantiles and maximum:",
        "",
        "| | p50 | p90 | p95 | p99 | max |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for kind in ("chunk", "paper"):
        q = summary[kind]["quantiles"]
        values = " | ".join(f"{q[str(x)]:.4f}" for x in QUANTILES)
        lines.append(f"| {kind} | {values} | {summary[kind]['max']:.4f} |")
    lines += [
        "",
        f"Sources at or above 0.5: {meta['above_half']}.",
        "",
        (
            "Limits: One random sample of the database, not of the sources the pipeline retrieves "
            "for a question; retrieved sources are topical and may score differently. The sample "
            "says how often a threshold would remove ordinary papers, not how many attacks it "
            "catches."
        ),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--chunks", type=int, default=200)
    parser.add_argument("--papers", type=int, default=200)
    parser.add_argument("--seed", default="d069")
    args = parser.parse_args()
    load_dotenv(find_dotenv(usecwd=True))
    dsn = os.environ.get("DATABASE_URL")
    if not dsn:
        parser.error("Set DATABASE_URL (the read-only app login) in .env.")

    from scilitrag.config import load_settings
    from scilitrag.contracts import Evidence
    from scilitrag.guardrails.evidence import build_component
    from scilitrag.rag.retrieval import paper_evidence

    chunk_rows, paper_rows = fetch(dsn, args.seed, args.chunks, args.papers)
    check = build_component(load_settings({**os.environ, "USE_MOCKS": "1"}))
    sources = [
        (
            f"chunk:{row['chunk_id']}",
            "chunk",
            Evidence(
                label=1,
                type="chunk",
                corpus_id=row["corpus_id"],
                chunk_id=row["chunk_id"],
                title=row["title"],
                section=row["section"],
                text=row["text"],
            ),
        )
        for row in chunk_rows
    ] + [
        (
            f"paper:{row['corpus_id']}",
            "paper",
            paper_evidence(row, has_passages=True).model_copy(update={"label": 1}),
        )
        for row in paper_rows
    ]
    started = time.perf_counter()
    records = [
        {"id": ident, "type": kind, "score": check([item]).scores.get(1, 0.0)}
        for ident, kind, item in sources
    ]
    summary = summarize(records)
    meta = {
        "seed": args.seed,
        "seconds": round(time.perf_counter() - started, 1),
        "above_half": sum(r["score"] >= 0.5 for r in records),
    }
    RESULT.write_text(
        json.dumps({"meta": meta, "summary": summary, "records": records}, indent=1) + "\n",
        encoding="utf-8",
    )
    REPORT.write_text(report(summary, meta), encoding="utf-8")
    top = sorted(zip(records, sources, strict=True), key=lambda p: -p[0]["score"])[:8]
    print(json.dumps(meta))
    for record, (_, _, item) in top:
        print(f"{record['score']:.4f} {record['id']} | {(item.title or '')[:70]}")


if __name__ == "__main__":
    main()
